const assert=require("node:assert/strict");
const {CANDIDATES,MIN_ENTRY_SCORE,analyzeSevenCandidatePool,sweepMssSignal}=require("../lib/dars-seven-candidate-paper");
assert.equal(MIN_ENTRY_SCORE,60);
assert.deepEqual(CANDIDATES.map(x=>x.id),["GOLD-583","GOLD-589","GOLD-580","GOLD-294","GOLD-257","GOLD-265","GOLD-425","DARS_EHL_BREAKOUT_V1_10"]);
assert.deepEqual(CANDIDATES.slice(0,3).map(x=>[x.sweepLookback,x.confirmBars]),[[5,4],[8,3],[5,3]]);
assert.equal(CANDIDATES[3].period,20);
assert.deepEqual(CANDIDATES.slice(4,6).map(x=>[x.period,x.lower,x.upper]),[[14,20,80],[14,30,70]]);
assert.deepEqual([CANDIDATES[6].period,CANDIDATES[6].lower,CANDIDATES[6].upper],[14,-80,-20]);
assert.equal(CANDIDATES[7].discovery,true);
assert.equal(analyzeSevenCandidatePool({frames:{},quote:{}}).setup,null);

const candles=Array.from({length:70},(_,i)=>({open:100,high:101,low:99,close:100,timeMs:Date.now()-(70-i)*300000}));
candles[68]={open:99.4,high:100.2,low:98,close:99.5,timeMs:candles[68].timeMs};
candles[69]={open:100.3,high:100.7,low:100.1,close:100.5,timeMs:candles[69].timeMs};
const sig=sweepMssSignal(candles,CANDIDATES[2],1);
assert.equal(sig.side,"BUY","a reclaimed sell-side sweep followed by a close above the sweep high is a bullish MSS");
const frame={ok:true,candles,atr14:1,regime:"RANGE_OR_TRANSITION",trend:"BULLISH"};
const frames={M5:frame,M15:{ok:true,regime:"TRENDING",trend:"BULLISH"},H1:{ok:true,regime:"TRENDING",trend:"BULLISH"}};
const result=analyzeSevenCandidatePool({frames,quote:{bid:100.3,ask:100.4},paperTrades:[]});
assert.equal(result.board.length,8);
assert.ok(result.board.some(x=>x.strategy==="GOLD-580"&&x.detected));
assert.ok(result.setup===null||result.setup.strategy==="GOLD-580"||result.setup.strategy==="GOLD-583"||result.setup.strategy==="GOLD-589");
assert.equal(result.setup?.side,"BUY");
assert.ok(result.setup?.takeProfit2>result.setup?.takeProfit1);
assert.equal(result.setup?.tp1Management,undefined,"TP1 management is exposed by the Robot API wrapper, not the raw strategy engine");
console.log("DARS eight-strategy Robot tests passed.");
