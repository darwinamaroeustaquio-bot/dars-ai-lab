create table if not exists public.mt5_history (
  id bigint generated by default as identity primary key,
  account text not null,
  record_type text not null check (record_type in ('candle','deal')),
  symbol text not null,
  timeframe text,
  record_time timestamptz not null,
  payload jsonb not null,
  created_at timestamptz not null default now(),
  unique (account, record_type, symbol, timeframe, record_time, payload)
);

alter table public.mt5_history enable row level security;

-- Keep this table inaccessible to anonymous/authenticated clients by default.
-- The Vercel API uses the service-role key server-side only.
